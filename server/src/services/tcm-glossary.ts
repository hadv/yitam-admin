/** Order here is also the priority order used for phrase hints. */
const SOURCES: Array<[TcmCategory, Row[]]> = [
  ['formula', FORMULAS],
  ['herb', HERBS],
  ['acupoint', ACUPOINTS],
  ['classic', CLASSICS],
  ['meridian', MERIDIANS],
  ['pulse', PULSES],
  ['diagnosis', DIAGNOSIS],
  ['theory', THEORY],
  ['disease', DISEASES],
  ['other', OTHER],
];

function buildGlossary(): GlossaryTerm[] {
  const seen = new Set<string>();
  const out: GlossaryTerm[] = [];
  for (const [category, rows] of SOURCES) {
    for (const [hans, hant, hanViet] of rows) {
      if (seen.has(hans)) continue; // defensive: keep first occurrence only
      seen.add(hans);
      out.push({ hans, hant, hanViet, category });
    }
  }
  return out;
}

/** Full glossary, ordered by hint priority (formulas, herbs, acupoints, classics, ...). */
export const TCM_GLOSSARY: GlossaryTerm[] = buildGlossary();

const MAX_HINT_CHARS = 100;

/**
 * Phrase hints for speech recognition, in the requested script.
 * Unique, prioritised (formulas, herbs, acupoints, classics first), each <= 100 chars.
 */
export function getTcmPhraseHints(script: 'hans' | 'hant', limit?: number): string[] {
  const max = typeof limit === 'number' && limit >= 0 ? Math.floor(limit) : Infinity;
  const seen = new Set<string>();
  const out: string[] = [];
  for (const term of TCM_GLOSSARY) {
    if (out.length >= max) break;
    const phrase = (script === 'hant' ? term.hant : term.hans).trim();
    if (!phrase || phrase.length > MAX_HINT_CHARS || seen.has(phrase)) continue;
    seen.add(phrase);
    out.push(phrase);
  }
  return out;
}

/** Chinese term -> Hán-Việt reading pairs, e.g. { zh: '当归', vi: 'Đương quy' }. */
export function getTcmHanVietPairs(
  script: 'hans' | 'hant' = 'hans',
  limit?: number
): Array<{ zh: string; vi: string }> {
  const max = typeof limit === 'number' && limit >= 0 ? Math.floor(limit) : Infinity;
  const seen = new Set<string>();
  const out: Array<{ zh: string; vi: string }> = [];
  for (const term of TCM_GLOSSARY) {
    if (out.length >= max) break;
    const zh = script === 'hant' ? term.hant : term.hans;
    if (seen.has(zh)) continue;
    seen.add(zh);
    out.push({ zh, vi: term.hanViet });
  }
  return out;
}

/**
 * Which Chinese script a BCP-47 code implies.
 * cmn-Hant-*, yue-Hant-*, zh-Hant*, zh/cmn-TW, zh/cmn-HK, zh/cmn-MO, and yue without an
 * explicit Hans subtag -> 'hant'; everything else (incl. undefined / 'auto') -> 'hans'.
 */
export function scriptForLanguageCode(code?: string): 'hans' | 'hant' {
  if (!code) return 'hans';
  const c = code.trim().toLowerCase().replace(/_/g, '-');
  if (/(^|-)hant(-|$)/.test(c)) return 'hant';
  if (/(^|-)hans(-|$)/.test(c)) return 'hans';
  if (/^(zh|cmn)-(tw|hk|mo)(-|$)/.test(c)) return 'hant';
  if (/^yue(-|$)/.test(c)) return 'hant';
  return 'hans';
}
